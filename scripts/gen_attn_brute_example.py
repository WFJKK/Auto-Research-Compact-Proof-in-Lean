#!/usr/bin/env python3
"""Write the scored brute-force example on a general (attention) network, with its instance split into one
kernel-decided theorem per input (examples/open_lane/attn_max2_tiny_scored).

    python3 scripts/gen_attn_brute_example.py <network.json> <module name suffix> <out dir> <charge per input>

The charge per input is the counted single rule's on this network (the same for every input: it depends
only on the shapes). The file is generated because the instance is long, not because anything in it is
trusted: every per-input theorem is checked by the kernel, and a wrong value fails to check.
"""
import json
import re
import sys
from itertools import product
from pathlib import Path

net_path, suffix, out_dir, charge = sys.argv[1], sys.argv[2], Path(sys.argv[3]), int(sys.argv[4])
net = json.loads(Path(net_path).read_text())
space = [net["graph"]["values"]] * net["graph"]["positions"]
inputs = [list(x) for x in product(*[range(v) for v in space])]
n = len(inputs)
prot = "N_" + re.sub(r"[^A-Za-z0-9]", "_", net["network"]) + f"_c{n}"
name = f"Candidate.{suffix}"

def ident(x):
    return "in_" + "_".join(str(t) for t in x)

facts = "\n".join(f"theorem {ident(x)} : run1 {x} = some (true, {charge}) := by\n  decide +kernel\n" for x in inputs)
listing = ", ".join(str(x) for x in inputs)
anon = ", ".join(ident(x) for x in inputs)

src = f'''import Protected.{prot}
import CompactCheck.Soundness
import CompactCheck.CountedOps
import CompactCheck.CountedGeneralSound

/-!
# A scored open-lane proof on an attention network: brute force through `gsingle`, the instance split

The checker runs the counted single rule for general networks (`I.gsingle`: the general checker's exact
forward pass, charged as cost-v3 charges a single leaf) on every input and counts the passes. The general
layer is the linear example's (`max2_tiny_scored`) with `gsingle` for `single` and `CostM.gsingle_correct`
for `singleOk_correct`.

The instance cannot be one `decide +kernel`: within one theorem the kernel's memory grows with every
forward pass (about 0.1 GB each on this network) and is released only when the theorem is done, and the
whole run did not fit in 8 GB. So each forward pass is its own theorem (`in_a_b`), decided by the kernel on
its own, and `countSingles_run` puts them together: the run of the checker is the runs of its calls in
sequence (`CostM.gsingle_run_of`). The facts compile in about two minutes at 2.5 GB. Generated by
`scripts/gen_attn_brute_example.py`; nothing in the generation is trusted, since the kernel checks every
theorem.
-/

namespace {name}

open CompactCheck Protected.{prot}

/-! ## General layer -/

/-- The single rule on each input of `xs`, counting the passes; each call is billed. -/
def countSingles (I : Interp) (g : Graph) (task : Task) : List Input → I.M I.N
  | [] => pure I.nzero
  | x :: xs => do
    let ok ← I.gsingle g task x
    let n ← countSingles I g task xs
    pure (I.nadd (I.countB ok) n)

/-- The checker: every input of the task's space. -/
def D : Checker := fun I => countSingles I graph task (allInputs task.space)

open Classical in
/-- `countSingles` never counts more than the inputs that are correct, for any weights and bill. -/
theorem countSingles_le (env : Env) : ∀ (xs : List Input) (c : Cost) (n : Nat) (c' : Cost),
    (countSingles Interp.counting graph task xs).run env c = some (n, c') →
    n ≤ xs.countP (fun x => decide (Correct graph env.weights task x))
  | [], c, n, c', h => by
    simp only [countSingles, CostM.run_pure, Option.some.injEq, Prod.mk.injEq] at h
    omega
  | x :: xs, c, n, c', h => by
    simp only [countSingles, CostM.run_bind] at h
    split at h
    · rename_i ok c1 hs
      split at h
      · rename_i m c2 hm
        have ih := countSingles_le env xs c1 m c2 hm
        rw [List.countP_cons]
        simp only [CostM.run_pure, Option.some.injEq, Prod.mk.injEq] at h
        cases ok with
        | false => simp only [Bool.cond_false, Nat.add_eq] at h; omega
        | true =>
          have hc : Correct graph env.weights task x := CostM.gsingle_correct hs
          simp only [Bool.cond_true, Nat.add_eq] at h
          simp only [hc, decide_true, ite_true]
          omega
      · cases h
    · cases h

theorem D_sound : ∀ (w : Weights ℚ) (c : Cert) (n : Nat) (cost : Cost),
    CostM.exec (D Interp.counting) ⟨w, c⟩ = some (n, cost) → n ≤ numCorrect graph w task := by
  intro w c n cost h
  unfold numCorrect
  exact countSingles_le ⟨w, c⟩ (allInputs task.space) [] n cost h

/-! ## Specific layer: one theorem per forward pass, then the glue -/

/-- `P` holds of every element, as a nested conjunction (a proof is one anonymous constructor). -/
def Each {{α : Type}} (P : α → Prop) : List α → Prop
  | [] => True
  | x :: xs => P x ∧ Each P xs

/-- The run of the checker is the runs of its calls in sequence. -/
theorem countSingles_run (env : Env) (K : Nat) : ∀ (xs : List Input) (c : Cost),
    Each (fun x => ((dweights env.weights).bind fun dw => gsingleRun graph dw task x) = some (true, K)) xs →
    ∃ c', (countSingles Interp.counting graph task xs).run env c = some (xs.length, c') ∧
      c'.total = c.total + K * xs.length
  | [], c, _ => ⟨c, by simp [countSingles, CostM.run_pure], by simp⟩
  | x :: xs, c, h => by
    obtain ⟨hx, hxs⟩ := h
    obtain ⟨c', hrun, htot⟩ := countSingles_run env K xs (c.add "single" K) hxs
    refine ⟨c', ?_, ?_⟩
    · have e : (x :: xs).length = 1 + xs.length := by simp only [List.length_cons]; omega
      rw [e]
      simp only [countSingles, Interp.counting_bind, Interp.counting_pure, CostM.run_bind,
        CostM.gsingle_run_of hx, hrun, CostM.run_pure, Bool.cond_true, Nat.add_eq]
    · rw [htot, Cost.total_add, List.length_cons, Nat.mul_add, Nat.mul_one]
      omega

/-- The counted single rule's verdict and charge on input `x` of the protected weights. -/
abbrev run1 (x : Input) : Option (Bool × Nat) := (dweights weights).bind fun dw => gsingleRun graph dw task x

{facts}
theorem inputs_eq : allInputs task.space = [{listing}] := by
  decide +kernel

theorem all_inputs : Each (fun x => run1 x = some (true, {charge})) (allInputs task.space) := by
  rw [inputs_eq]
  exact ⟨{anon}, trivial⟩

/-- The kernel never runs the whole checker at once: the instance follows from the {n} facts.

    Every step rewrites with an equation (`CostM.billed`, `CostM.exec`, the checker's definition `hD`, the
    glue's `hrun`), so the terms the kernel compares are identical. Asking it to compare two different
    `CostM.run` terms by unfolding (an `exact hrun` against the unrewritten goal, say) makes it unfold the
    structure projection first, which runs the whole checker: the evaluation this proof avoids. -/
theorem D_instance : CostM.billed (D Interp.counting) ⟨weights, cert⟩ = some ({n}, {n} * {charge}) := by
  obtain ⟨c', hrun, htot⟩ := countSingles_run ⟨weights, cert⟩ {charge} (allInputs task.space) [] all_inputs
  have hlen : (allInputs task.space).length = {n} := by simp [inputs_eq]
  have htot' : c'.total = {n} * {charge} := by
    rw [htot, hlen]
    simp [Cost.total]
  have hD : D Interp.counting = countSingles Interp.counting graph task (allInputs task.space) := rfl
  rw [CostM.billed, CostM.exec, hD, hrun, hlen]
  simp only [Option.map_some, htot']

theorem performance : Target := by
  show claimedCount ≤ numCorrect graph weights task
  obtain ⟨cost, h⟩ := CostM.exec_of_billed D_instance
  exact D_sound weights cert {n} cost h

end {name}
'''
out_dir.mkdir(parents=True, exist_ok=True)
(out_dir / "Candidate").mkdir(exist_ok=True)
(out_dir / "Candidate" / f"{suffix}.lean").write_text(src)
manifest = {"schema": "open-lane-candidate-v1", "candidate_id": out_dir.name.replace("_", "-"), "model": sys.argv[5] if len(sys.argv) > 5 else "tests/attn_max2_tiny",
            "network": net["network"], "claimed_count": n, "theorem": f"{name}.performance",
            "modules": [f"Candidate/{suffix}.lean"],
            "scored": {"checker": f"{name}.D", "sound": f"{name}.D_sound", "instance": f"{name}.D_instance",
                       "certificate": [], "claimed_bill": n * charge}}
(out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
print(f"wrote {out_dir} ({n} inputs, bill {n * charge})")
