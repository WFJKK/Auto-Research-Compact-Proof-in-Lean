#!/usr/bin/env python3
"""Write a scored example that certifies an attention network with token_interval leaves
(examples/open_lane/attn_max2_tiny_tokens): the maximum-knowledge condition's `I.gtokenIntervals` on a list
of boxes, the instance split into one kernel-decided theorem per leaf.

    python3 scripts/gen_attn_tokens_example.py <network.json> <boxes.json> <module name suffix> <out dir> <model>

<model> is the network's model folder in the pipeline repository (tests/attn_max2_tiny), for the manifest.

The boxes are the checker's leaves: no two may share an input, and each must lie in the input space (the
soundness proof decides both). `compactcheck gtokens` gives each leaf's verdict, charge and requests for
rows; they are written as the facts. Nothing in the generation is trusted: the kernel checks every fact,
and a wrong value fails to check.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CHECKER = HERE.parent / ".lake" / "build" / "bin" / "compactcheck"

net_path, boxes_path, suffix, out_dir, model = sys.argv[1], sys.argv[2], sys.argv[3], Path(sys.argv[4]), sys.argv[5]
net = json.loads(Path(net_path).read_text())
boxes = json.loads(Path(boxes_path).read_text())
positions, values = net["graph"]["positions"], net["graph"]["values"]
n_inputs = values ** positions
prot = "N_" + re.sub(r"[^A-Za-z0-9]", "_", net["network"]) + f"_c{n_inputs}"
name = f"Candidate.{suffix}"

out = subprocess.run([str(CHECKER), "gtokens", net_path, boxes_path], capture_output=True, text=True, check=True)
rows = [json.loads(line) for line in out.stdout.splitlines() if line.startswith("{")]
leaves = [r for r in rows if "box" in r]
total = rows[-1]
if any(r.get("status") == "rejected" for r in leaves) or "verdicts" not in total:
    sys.exit("the token_interval rule rejects one of the boxes")
count = 0
for r in leaves:
    if r["verdict"]:
        size = 1
        for lo, hi in r["box"]:
            size *= hi - lo + 1
        count += size
bill = total["token_interval"] + total["tables"]


def lean_box(b):
    return "[" + ", ".join(f"⟨{lo}, {hi}⟩" for lo, hi in b) + "]"


def lean_req(q):
    return "⟨[" + ", ".join(map(str, q["key"])) + f"], {q['lo']}, {q['hi']}, {q['cost']}⟩"


def lean_result(r):
    reqs = ",\n    ".join(lean_req(q) for q in r["reqs"])
    return f"({str(r['verdict']).lower()}, {r['token_interval']}, [\n    {reqs}])"


box_list = ",\n  ".join(lean_box(r["box"]) for r in leaves)
results = ",\n  ".join(lean_result(r) for r in leaves)
facts = "\n".join(
    f"theorem leaf_{i} : leaf1 {lean_box(r['box'])} = some (results.getD {i} default) := by\n  decide +kernel\n"
    for i, r in enumerate(leaves))
anon = ", ".join(f"leaf_{i}" for i in range(len(leaves)))

src = f'''import Protected.{prot}
import CompactCheck.Soundness
import CompactCheck.CountedOps
import CompactCheck.CountedGeneralSound

/-!
# A scored open-lane proof on an attention network with token_interval leaves

The maximum-knowledge condition's token_interval rule (`I.gtokenIntervals`: the general checker's
token_interval leaf on each box, charged as cost-v3 charges a proof's token_interval leaves) on {len(leaves)}
boxes that cover the input space: for each largest token `m`, the inputs with `m` at the first position and
at most `m` at the second, and those with `m` at the second and less than `m` at the first. Each box has a
constant label, the rule keeps each input's value exactly along the one position that varies, and the rows
that depend on their token alone (the embeddings and their products with the weights) are computed and
charged once for all the boxes, which is why one call takes them all.

Soundness: the rule's verdicts (`CostM.gtokenIntervals_correct`), and the count of the inputs of the
boxes answered `true`, which is at most the number answered correctly because no two boxes share an input
(`certifiedCount_le_numCorrect`; `pairwiseApart` and `fits` decided on the boxes).

The instance: one theorem per box (`leaf_i`), each decided by the kernel on its own, as in the brute-force
example (the kernel's memory grows within a theorem), put together by `CostM.gtokenIntervals_run_of_facts`;
then the bill is a computation on the facts' small lists of requests. Generated by
`scripts/gen_attn_tokens_example.py`; nothing in the generation is trusted.
-/

namespace {name}

open CompactCheck Protected.{prot}

/-! ## General layer -/

/-- The leaves. -/
def boxes : List Box := [
  {box_list}]

/-- The inputs of the boxes answered `true`. -/
def tally (I : Interp) : List Box → List I.B → I.N
  | b :: bs, v :: vs => I.nadd (I.nscale (boxSize b) v) (tally I bs vs)
  | _, _ => I.nzero

/-- The checker: the token_interval rule on every box, in one call. -/
def D : Checker := fun I => do
  let vs ← I.gtokenIntervals graph task boxes
  pure (tally I boxes vs)

theorem tally_counting : ∀ (bs : List Box) (vs : List Bool),
    tally Interp.counting bs vs = certifiedCount bs vs
  | b :: bs, v :: vs => by
    simp only [tally, certifiedCount, tally_counting bs vs]
    rfl
  | [], _ => rfl
  | _ :: _, [] => rfl

theorem boxes_apart : pairwiseApart boxes = true := by decide

theorem boxes_fit : (boxes.all fun b => fits b task.space) = true := by decide

/-- The run of the checker is the run of its one call, for any weights and bill. Stated with the
    environment and the bill as variables, so that its proof never meets the protected weights. -/
theorem D_run {{env : Env}} {{c c' : Cost}} {{vs : List Bool}}
    (h : (CostM.gtokenIntervals graph task boxes).run env c = some (vs, c')) :
    (D Interp.counting).run env c = some (tally Interp.counting boxes vs, c') := by
  have hD : D Interp.counting = (CostM.gtokenIntervals graph task boxes >>= fun vs =>
      (pure (tally Interp.counting boxes vs) : CostM Nat)) := rfl
  rw [hD, CostM.run_bind, h]
  rfl

theorem D_sound : ∀ (w : Weights ℚ) (c : Cert) (n : Nat) (cost : Cost),
    CostM.exec (D Interp.counting) ⟨w, c⟩ = some (n, cost) → n ≤ numCorrect graph w task := by
  intro w c n cost h
  have hD : D Interp.counting = (CostM.gtokenIntervals graph task boxes >>= fun vs =>
      (pure (tally Interp.counting boxes vs) : CostM Nat)) := rfl
  rw [CostM.exec, hD, CostM.run_bind] at h
  split at h
  · rename_i vs c1 hrun
    rw [CostM.run_pure, Option.some.injEq, Prod.mk.injEq] at h
    rw [← h.1, tally_counting]
    exact certifiedCount_le_numCorrect boxes_apart boxes_fit (CostM.gtokenIntervals_correct hrun).2
  · cases h

/-! ## Specific layer: one theorem per box, then the glue -/

/-- The token_interval rule's verdict, charge and requests for rows on box `b` of the protected weights. -/
abbrev leaf1 (b : Box) : Option (Bool × Nat × List RowReq) :=
  (dweights weights).bind fun dw => gtokenLeaf graph dw task b

/-- What `compactcheck gtokens` reports for each box, in order. -/
def results : List (Bool × Nat × List RowReq) := [
  {results}]

{facts}
theorem facts : TokenLeafFacts ⟨weights, cert⟩ graph task boxes results :=
  ⟨{anon}, trivial⟩

/-- The kernel never runs the whole checker at once: the call's run comes from the facts
    (`CostM.gtokenIntervals_run_of_facts`), the checker's run from the call's (`D_run`), and the rest is
    arithmetic on the facts' small lists. Each step rewrites with an equation whose sides are the goal's
    own terms. Where two terms differ only by a definitional unfolding under `CostM.run` (`Nat` for
    `Interp.counting.N`, say), the kernel unfolds the run before it compares them, and that evaluates
    every leaf at once: `D_run` is stated for any environment, so its proof never meets the weights. -/
theorem D_instance : CostM.billed (D Interp.counting) ⟨weights, cert⟩ = some ({count}, {bill}) := by
  rw [CostM.billed, CostM.exec, D_run (CostM.gtokenIntervals_run_of_facts (by decide) facts)]
  decide +kernel

theorem performance : Target := by
  show claimedCount ≤ numCorrect graph weights task
  obtain ⟨cost, h⟩ := CostM.exec_of_billed D_instance
  exact D_sound weights cert {count} cost h

end {name}
'''

module = suffix.split(".")[-1]
(out_dir / "Candidate").mkdir(parents=True, exist_ok=True)
(out_dir / "Candidate" / f"{module}.lean").write_text(src)
manifest = {
    "schema": "open-lane-candidate-v1",
    "candidate_id": out_dir.name.replace("_", "-"),
    "model": model,
    "network": net["network"],
    "claimed_count": count,
    "theorem": f"{name}.performance",
    "modules": [f"Candidate/{module}.lean"],
    "scored": {"checker": f"{name}.D", "sound": f"{name}.D_sound", "instance": f"{name}.D_instance",
               "certificate": [], "claimed_bill": bill},
}
(out_dir / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n")
print(f"wrote {out_dir}: {len(leaves)} leaves, count {count}, bill {bill}")
