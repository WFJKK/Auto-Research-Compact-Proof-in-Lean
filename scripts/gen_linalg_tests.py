#!/usr/bin/env python3
"""Generate CompactCheck/LinAlgRandomTest.lean: random tests for LinAlg.lean.

Two kinds of test:

* Differential: every operation is recomputed here with Python's exact
  fractions, by code written independently of the Lean code, and Lean must
  give the same answer.
* Property: on random data, Lean checks the laws that the soundness proofs
  will rely on (a one-hot vector picks a column, contraction with biases
  computes the same function, boxDotLower is a lower bound, and so on).

Rerun after changing LinAlg.lean, from the project folder:

    python3 scripts/gen_linalg_tests.py > CompactCheck/LinAlgRandomTest.lean
"""

import random
from fractions import Fraction as Q

SEED = 20261013
rng = random.Random(SEED)

# Mostly dyadic denominators, like float32 weights, plus 3 to exercise
# general rationals.
DENOMS = [1, 1, 2, 4, 8, 3]


# --- random data ---------------------------------------------------------


def rq(lo=-9, hi=9):
    return Q(rng.randint(lo, hi), rng.choice(DENOMS))


def rvec(n, pool=None):
    if pool is not None:
        return [Q(rng.choice(pool)) for _ in range(n)]
    return [rq() for _ in range(n)]


def rmat(m, n):
    return [rvec(n) for _ in range(m)]


def rnonneg(n):
    return [abs(rq(0, 6)) for _ in range(n)]


def rrange(n):
    """0 <= lo <= t <= hi < n."""
    a, b, c = sorted(rng.randint(0, n - 1) for _ in range(3))
    return a, b, c


# --- independent Python reference -----------------------------------------


def vec_get(v, i):
    return v[i] if i < len(v) else Q(0)


def vec_add(a, b):
    return [x + y for x, y in zip(a, b)]


def vec_sub(a, b):
    return [x - y for x, y in zip(a, b)]


def vec_dot(a, b):
    return sum((x * y for x, y in zip(a, b)), Q(0))


def vec_abs(v):
    return [abs(x) for x in v]


def vec_sum_list(n, vs):
    acc = [Q(0)] * n
    for v in vs:
        acc = vec_add(acc, v)
    return acc


def list_max(v):
    return max(v) if v else Q(0)


def list_min(v):
    return min(v) if v else Q(0)


def strict_max_at(v, l):
    return l < len(v) and all(v[j] < v[l] for j in range(len(v)) if j != l)


def all_pos_except(v, l):
    return all(j == l or x > 0 for j, x in enumerate(v))


def box_dot_lower(c, ce, r):
    return vec_dot(c, ce) - vec_dot(vec_abs(c), r)


def mat_transpose(W):
    return [list(col) for col in zip(*W)]


def mat_mul(A, B):
    n = len(B[0]) if B else 0
    return [[sum((A[i][k] * B[k][j] for k in range(len(B))), Q(0)) for j in range(n)] for i in range(len(A))]


def mat_max_abs(W):
    return max((abs(x) for row in W for x in row), default=Q(0))


def mat_row_diffs(W, l):
    rl = W[l] if l < len(W) else []
    return [vec_sub(rl, row) for row in W]


def low_rank_lower(Fm, G, l, j, lo, hi):
    """The Python checker's own formula (core/check/approx.py, low_rank)."""
    c = [a - b for a, b in zip(Fm[l], Fm[j])]
    gmin = [min(row[lo : hi + 1]) for row in G]
    gmax = [max(row[lo : hi + 1]) for row in G]
    return sum((ck * (gmin[k] if ck >= 0 else gmax[k]) for k, ck in enumerate(c)), Q(0))


def in_box(x, ce, r):
    return len(x) == len(ce) == len(r) and all(abs(a - b) <= s for a, b, s in zip(x, ce, r))


# --- Lean literals ----------------------------------------------------------


def q(x):
    x = Q(x)
    return str(x.numerator) if x.denominator == 1 else f"{x.numerator}/{x.denominator}"


def vec(v):
    return "[" + ", ".join(q(x) for x in v) + "]"


def mat(W):
    return "[" + ", ".join(vec(r) for r in W) + "]"


def V(v):
    return f"({vec(v)} : Vec)"


def M(W):
    return f"({mat(W)} : Mat)"


def R(x):
    return f"({q(x)} : Rat)"


def B(b):
    return "true" if b else "false"


# --- output -----------------------------------------------------------------

HEADER = f'''import CompactCheck.LinAlg

/-!
# Random tests for `LinAlg.lean`

Generated by `scripts/gen_linalg_tests.py` (seed {SEED}); do not edit by
hand. Rerun the script after changing `LinAlg.lean`.

* Differential tests: the expected values come from Python's exact
  fractions, computed by code written independently of the Lean code.
* Property tests: Lean checks, on random data, the laws that the
  soundness proofs will rely on.

The build fails if any `#guard` is false.
-/

namespace LinAlgTest.Random

open CompactCheck

/-! ## Helpers -/

/-- `a ≤ b` entrywise, for vectors of the same length. -/
def vecLe (a b : Vec) : Bool :=
  a.length == b.length && (a.zip b).all fun (x, y) => x ≤ y

/-- `x` lies in the box: `|x - centre| ≤ radius` entrywise. -/
def inBoxVec (x centre radius : Vec) : Bool :=
  x.length == centre.length && centre.length == radius.length &&
    ((vecSub x centre).zip radius).all fun (d, r) => ratAbs d ≤ r

/-- The lower bound of the low-rank approximation: with `P = F G`, the
    margin of output `l` over output `j`, over columns `lo` to `hi`. -/
def lowRankLower (F G : Mat) (l j lo hi : Nat) : Rat :=
  let c := matRow (matRowDiffs F l) j
  let mn := minOverCols G lo hi
  let mx := maxOverCols G lo hi
  boxDotLower c (vecScale (1/2) (vecAdd mn mx)) (vecScale (1/2) (vecSub mx mn))

/-! ## Properties -/

/-- A one-hot vector picks out a column. -/
def propOneHot (W : Mat) (t : Nat) : Bool :=
  matVec W (oneHot (matNumCols W) t) == matCol W t

/-- Transposing twice gives the matrix back. -/
def propTransposeTwice (W : Mat) : Bool :=
  matTranspose (matTranspose W) == W

/-- `(A B) x = A (B x)`. -/
def propMulVec (A B : Mat) (x : Vec) : Bool :=
  matVec (matMul A B) x == matVec A (matVec B x)

/-- `(A B) C = A (B C)`. -/
def propMulAssoc (A B C : Mat) : Bool :=
  matMul (matMul A B) C == matMul A (matMul B C)

/-- The contract rule: two linear maps with biases compute the same as one
    map, whose weight is the product and whose bias is pushed through. -/
def propContract (W1 : Mat) (b1 : Vec) (W2 : Mat) (b2 : Vec) (x : Vec) : Bool :=
  vecAdd (matVec W2 (vecAdd (matVec W1 x) b1)) b2 ==
    vecAdd (matVec (matMul W2 W1) x) (vecAdd (matVec W2 b1) b2)

/-- `boxDotLower` is a lower bound on `c · x` for `x` in the box. -/
def propBoxLower (c centre radius x : Vec) : Bool :=
  inBoxVec x centre radius && decide (boxDotLower c centre radius ≤ vecDot c x)

/-- `boxDotLower` is attained at a corner of the box. -/
def propBoxCorner (c centre radius corner : Vec) : Bool :=
  inBoxVec corner centre radius && vecDot c corner == boxDotLower c centre radius

/-- Boxes through a linear map: if `x` is in the box with centre `c` and
    radius `r`, then `W x + b` is in the box with centre `W c + b` and
    radius `|W| r`. -/
def propLinearBox (W : Mat) (b centre radius x : Vec) : Bool :=
  inBoxVec x centre radius &&
    inBoxVec (vecAdd (matVec W x) b) (vecAdd (matVec W centre) b) (matVec (matAbs W) radius)

/-- The one-hot step of the interval rule: column `t` of `W`, for `t` in
    `[lo, hi]`, lies in the box built from the min and max over those
    columns. -/
def propColumnInBox (W : Mat) (lo hi t : Nat) : Bool :=
  let mn := minOverCols W lo hi
  let mx := maxOverCols W lo hi
  inBoxVec (matCol W t) (vecScale (1/2) (vecAdd mn mx)) (vecScale (1/2) (vecSub mx mn))

/-- Margins after a full contraction: the min over columns `lo` to `hi` of
    `W_l - W_j` is at most the margin at any column `t` in that range. -/
def propMarginMin (W : Mat) (l lo hi t : Nat) : Bool :=
  let D := matRowDiffs W l
  vecLe (minOverCols D lo hi) (matCol D t)

/-- The approximate rule: with `eps = max |W - P|`, the margins of `P`
    minus `2 eps` are at most the margins of `W`. -/
def propApprox (W P : Mat) (l t : Nat) : Bool :=
  let eps := matMaxAbs (matSub W P)
  vecLe (vecShift (-2 * eps) (matCol (matRowDiffs P l) t)) (matCol (matRowDiffs W l) t)

/-- The low-rank form: the bound is at most the true margin of `P = F G`
    at any column `t` in `[lo, hi]`. -/
def propLowRank (F G : Mat) (l j lo hi t : Nat) : Bool :=
  decide (lowRankLower F G l j lo hi ≤ matGet (matRowDiffs (matMul F G) l) j t)
'''


def main():
    out = [HEADER]

    def section(title):
        out.append(f"\n/-! ## {title} -/\n")

    def g(line):
        out.append("#guard " + line)

    # ---- differential: vectors ----
    section("Differential: vectors")
    for _ in range(12):
        a, b = rvec(rng.randint(0, 5)), rvec(rng.randint(0, 5))
        g(f"vecAdd {V(a)} {V(b)} == {V(vec_add(a, b))}")
    for _ in range(12):
        a, b = rvec(rng.randint(0, 5)), rvec(rng.randint(0, 5))
        g(f"vecSub {V(a)} {V(b)} == {V(vec_sub(a, b))}")
    for _ in range(12):
        a, b = rvec(rng.randint(0, 5)), rvec(rng.randint(0, 5))
        g(f"vecDot {V(a)} {V(b)} == {R(vec_dot(a, b))}")
    for _ in range(8):
        c, v = rq(), rvec(rng.randint(0, 5))
        g(f"vecScale {R(c)} {V(v)} == {V([c * x for x in v])}")
    for _ in range(8):
        c, v = rq(), rvec(rng.randint(0, 5))
        g(f"vecShift {R(c)} {V(v)} == {V([x + c for x in v])}")
    for _ in range(8):
        v = rvec(rng.randint(0, 5))
        g(f"vecAbs {V(v)} == {V(vec_abs(v))}")
    for _ in range(12):
        v = rvec(rng.randint(0, 6))
        lo, hi = rng.randint(0, 7), rng.randint(0, 7)
        g(f"vecSlice {V(v)} {lo} {hi} == {V(v[lo : hi + 1])}")
    for _ in range(10):
        n = rng.randint(0, 4)
        vs = [rvec(n if rng.random() < 0.8 else rng.randint(0, 5)) for _ in range(rng.randint(0, 4))]
        g(f"vecSumList {n} {M(vs)} == {V(vec_sum_list(n, vs))}")
    for _ in range(10):
        v = rvec(rng.randint(0, 6), pool=[-3, -1, 0, 1, 2, 2])
        g(f"listMax {V(v)} == {R(list_max(v))}")
    for _ in range(10):
        v = rvec(rng.randint(0, 6), pool=[-3, -1, 0, 1, 2, 2])
        g(f"listMin {V(v)} == {R(list_min(v))}")
    for _ in range(8):
        n, t = rng.randint(0, 5), rng.randint(0, 6)
        g(f"oneHot {n} {t} == {V([Q(1) if i == t else Q(0) for i in range(n)])}")

    # ---- differential: margins and the final test ----
    section("Differential: margins and the final test")
    for _ in range(8):
        v, l = rvec(rng.randint(0, 5)), rng.randint(0, 6)
        g(f"marginsAt {V(v)} {l} == {V([vec_get(v, l) - x for x in v])}")
    for _ in range(12):
        v, l = rvec(rng.randint(0, 5), pool=[-1, 0, Q(1, 2), 2]), rng.randint(0, 5)
        g(f"allPosExcept {V(v)} {l} == {B(all_pos_except(v, l))}")
    for _ in range(20):
        v, l = rvec(rng.randint(0, 5), pool=[-1, 0, 1, 2]), rng.randint(0, 6)
        g(f"strictMaxAt {V(v)} {l} == {B(strict_max_at(v, l))}")
    for _ in range(10):
        n = rng.randint(0, 5)
        c, ce, r = rvec(n), rvec(n), rnonneg(n)
        g(f"boxDotLower {V(c)} {V(ce)} {V(r)} == {R(box_dot_lower(c, ce, r))}")

    # ---- differential: matrices ----
    section("Differential: matrices")
    for _ in range(8):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W, t = rmat(m, n), rng.randint(0, n)
        g(f"matCol {M(W)} {t} == {V([vec_get(row, t) for row in W])}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W, x = rmat(m, n), rvec(n)
        g(f"matVec {M(W)} {V(x)} == {V([vec_dot(row, x) for row in W])}")
    for _ in range(8):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        A, Bm = rmat(m, n), rmat(m, n)
        g(f"matSub {M(A)} {M(Bm)} == {M([vec_sub(r, s) for r, s in zip(A, Bm)])}")
    for _ in range(6):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W = rmat(m, n)
        g(f"matAbs {M(W)} == {M([vec_abs(r) for r in W])}")
    for _ in range(8):
        m, n = rng.randint(0, 4), rng.randint(0, 4)
        W = rmat(m, n)
        g(f"matMaxAbs {M(W)} == {R(mat_max_abs(W))}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W = rmat(m, n)
        g(f"matTranspose {M(W)} == {M(mat_transpose(W))}")
    for _ in range(10):
        m, k, n = rng.randint(1, 4), rng.randint(1, 4), rng.randint(1, 4)
        A, Bm = rmat(m, k), rmat(k, n)
        g(f"matMul {M(A)} {M(Bm)} == {M(mat_mul(A, Bm))}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 5)
        W = rmat(m, n)
        lo, _, hi = rrange(n)
        g(f"minOverCols {M(W)} {lo} {hi} == {V([min(r[lo : hi + 1]) for r in W])}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 5)
        W = rmat(m, n)
        lo, _, hi = rrange(n)
        g(f"maxOverCols {M(W)} {lo} {hi} == {V([max(r[lo : hi + 1]) for r in W])}")
    for _ in range(8):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W, l = rmat(m, n), rng.randint(0, m - 1)
        g(f"matRowDiffs {M(W)} {l} == {M(mat_row_diffs(W, l))}")
    for _ in range(10):
        m, n = rng.randint(0, 3), rng.randint(0, 3)
        W = rmat(m, n)
        if W and rng.random() < 0.4:
            W[rng.randrange(m)] = rvec(rng.randint(0, 4))  # sometimes ragged
        qm = m if rng.random() < 0.7 else rng.randint(0, 3)
        qn = n if rng.random() < 0.7 else rng.randint(0, 3)
        expect = len(W) == qm and all(len(r) == qn for r in W)
        g(f"matHasShape {M(W)} {qm} {qn} == {B(expect)}")
    for _ in range(8):
        m, r, n = rng.randint(2, 4), rng.randint(1, 3), rng.randint(1, 5)
        Fm, G = rmat(m, r), rmat(r, n)
        l, j = rng.randint(0, m - 1), rng.randint(0, m - 1)
        lo, _, hi = rrange(n)
        g(f"lowRankLower {M(Fm)} {M(G)} {l} {j} {lo} {hi} == {R(low_rank_lower(Fm, G, l, j, lo, hi))}")

    # ---- properties ----
    section("Properties")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 5)
        g(f"propOneHot {M(rmat(m, n))} {rng.randint(0, n - 1)}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        g(f"propTransposeTwice {M(rmat(m, n))}")
    for _ in range(10):
        m, k, n = rng.randint(1, 4), rng.randint(1, 4), rng.randint(1, 4)
        g(f"propMulVec {M(rmat(m, k))} {M(rmat(k, n))} {V(rvec(n))}")
    for _ in range(10):
        a, b, c, d = (rng.randint(1, 3) for _ in range(4))
        g(f"propMulAssoc {M(rmat(a, b))} {M(rmat(b, c))} {M(rmat(c, d))}")
    for _ in range(10):
        n, h, o = rng.randint(1, 4), rng.randint(1, 4), rng.randint(1, 4)
        g(f"propContract {M(rmat(h, n))} {V(rvec(h))} {M(rmat(o, h))} {V(rvec(o))} {V(rvec(n))}")
    for _ in range(10):
        n = rng.randint(0, 5)
        c, ce, r = rvec(n), rvec(n), rnonneg(n)
        x = [a + rng.choice([-1, Q(-1, 2), 0, Q(1, 3), 1]) * s for a, s in zip(ce, r)]
        assert in_box(x, ce, r) and box_dot_lower(c, ce, r) <= vec_dot(c, x)
        g(f"propBoxLower {V(c)} {V(ce)} {V(r)} {V(x)}")
    for _ in range(10):
        n = rng.randint(0, 5)
        c, ce, r = rvec(n), rvec(n), rnonneg(n)
        corner = [a - s if ck > 0 else a + s if ck < 0 else a for ck, a, s in zip(c, ce, r)]
        assert vec_dot(c, corner) == box_dot_lower(c, ce, r)
        g(f"propBoxCorner {V(c)} {V(ce)} {V(r)} {V(corner)}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W, b, ce, r = rmat(m, n), rvec(m), rvec(n), rnonneg(n)
        x = [a + rng.choice([-1, Q(-1, 2), 0, Q(1, 3), 1]) * s for a, s in zip(ce, r)]
        g(f"propLinearBox {M(W)} {V(b)} {V(ce)} {V(r)} {V(x)}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 5)
        lo, t, hi = rrange(n)
        g(f"propColumnInBox {M(rmat(m, n))} {lo} {hi} {t}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 5)
        lo, t, hi = rrange(n)
        g(f"propMarginMin {M(rmat(m, n))} {rng.randint(0, m - 1)} {lo} {hi} {t}")
    for _ in range(10):
        m, n = rng.randint(1, 4), rng.randint(1, 4)
        W = rmat(m, n)
        P = [[x + rq(-2, 2) / 4 for x in row] for row in W]
        g(f"propApprox {M(W)} {M(P)} {rng.randint(0, m - 1)} {rng.randint(0, n - 1)}")
    for _ in range(10):
        m, r, n = rng.randint(2, 4), rng.randint(1, 3), rng.randint(1, 5)
        lo, t, hi = rrange(n)
        l, j = rng.randint(0, m - 1), rng.randint(0, m - 1)
        g(f"propLowRank {M(rmat(m, r))} {M(rmat(r, n))} {l} {j} {lo} {hi} {t}")

    out.append("\nend LinAlgTest.Random\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
